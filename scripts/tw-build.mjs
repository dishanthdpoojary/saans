// Builds the app stylesheet with Tailwind's Node API.
//
// Why: Windows Application Control on the dev machine blocks Tailwind's native file scanner and its
// WASM fallback cannot read the file system, so the standard loader emitted no utilities. Here the
// scan is plain Node, and src/app/globals.css (the authored source) compiles to
// src/app/styles.generated.css, which the layout imports. Same output on every OS, including Vercel.
//
//   node scripts/tw-build.mjs           build once
//   node scripts/tw-build.mjs --watch   rebuild on source changes
import { compile } from "@tailwindcss/node";
import { readdirSync, readFileSync, statSync, writeFileSync, watch } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const SRC = fileURLToPath(new URL("../src", import.meta.url));
const INPUT = join(SRC, "app", "globals.css");
const OUTPUT = join(SRC, "app", "styles.generated.css");

function candidates() {
  const files = [];
  const walk = (d) => {
    for (const f of readdirSync(d)) {
      const p = join(d, f);
      if (statSync(p).isDirectory()) walk(p);
      else if (/\.(tsx?|jsx?)$/.test(f)) files.push(p);
    }
  };
  walk(SRC);
  const tokens = new Set();
  const strRe = /(["'`])((?:\\.|(?!\1)[^\\])*?)\1/g;
  const tokRe = /^[!-]?[a-z0-9@[][a-z0-9:\-_[\]/.%#(),!@&>~*=']*$/i;
  for (const f of files) {
    for (const m of readFileSync(f, "utf8").matchAll(strRe)) {
      for (const t of m[2].split(/\s+/)) if (t && t.length < 90 && tokRe.test(t) && !t.includes("${")) tokens.add(t);
    }
  }
  return [...tokens];
}

async function build() {
  const t0 = Date.now();
  const css = readFileSync(INPUT, "utf8");
  const compiler = await compile(css, { base: dirname(INPUT), onDependency() {} });
  const out = compiler.build(candidates());
  const header = "/* generated by scripts/tw-build.mjs from globals.css; do not edit */\n";
  let prev = "";
  try {
    prev = readFileSync(OUTPUT, "utf8");
  } catch {}
  if (prev !== header + out) writeFileSync(OUTPUT, header + out);
  console.log(`[tw-build] ${out.length} bytes in ${Date.now() - t0} ms`);
}

await build();
if (process.argv.includes("--watch")) {
  let timer;
  watch(SRC, { recursive: true }, (_e, file) => {
    if (!file || file.endsWith("styles.generated.css")) return;
    clearTimeout(timer);
    timer = setTimeout(() => build().catch((e) => console.error("[tw-build]", e.message)), 120);
  });
  console.log("[tw-build] watching src/");
}
